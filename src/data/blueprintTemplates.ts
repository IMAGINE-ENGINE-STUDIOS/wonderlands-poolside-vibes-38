/**
 * Sheet templates, note libraries and schedule seeds for the Blueprint Builder.
 *
 * Seeded from a certified Florida engineered pool/patio permit set
 * (Pasco County / Port Richey, FBC 2023 8th Edition + 2023 NEC) so every
 * generated plan set starts from a real, code-referenced baseline.
 */

export interface NoteGroup {
  id: string;
  title: string;
  /** Notes are numbered in the order listed */
  notes: string[];
}

export interface SheetTemplate {
  /** Drawing number, e.g. A1 */
  code: string;
  description: string;
  /** Note groups printed on this sheet */
  noteGroups: string[];
  /** Info tables printed on this sheet */
  tables: BlueprintTableId[];
  /** True when the sheet carries the drawn site plan */
  hasSitePlan?: boolean;
  /** Detail callouts listed on the sheet */
  details?: string[];
}

export type BlueprintTableId =
  | 'areas'
  | 'poolData'
  | 'equipmentLegend'
  | 'equipmentOptions'
  | 'scopeOfWork'
  | 'referenceCodes';

